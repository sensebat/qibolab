"""Teeth matrix: which tests of the ZI suite each planted driver bug turns red.

As a pytest plugin, ``--mutant <name>`` plants one bug of :data:`mutants.MUTANTS` in
every test of the run and deselects the ``[mutant-...]`` cases of ``@kills`` (the
``[driver]`` case then runs on the mutated driver). ``--teeth-out <file>`` writes, for
each test that did not pass, the exception that made it fail.

As a script, it runs the whole ZI suite once on the driver and once per mutant, and
writes TEETH.md next to this file::

    python -m tests.instruments.zi.conformance.teeth [--jobs 4] [-k <mutant substring>]

Tests that do not pass on the driver itself are left out of the matrix.

Pattern: mutation testing as in mutmut / cosmic-ray (one run of the suite per mutant,
a surviving mutant is a gap in the suite).
"""

import argparse
import json
import subprocess
import sys
import tempfile
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from importlib.metadata import version
from pathlib import Path

import pytest

HERE = Path(__file__).parent
ROOT = HERE.parents[3]
SUITE = "tests/instruments/zi"
PLUGIN = "tests.instruments.zi.conformance.teeth"


# plugin


def pytest_addoption(parser):
    group = parser.getgroup("teeth")
    group.addoption("--mutant", default=None, help="Plant this mutant in every test.")
    group.addoption("--teeth-out", default=None, help="Write failures as JSON here.")


@pytest.fixture(autouse=True)
def _planted_bug(request, monkeypatch):
    name = request.config.getoption("--mutant")
    if name is not None:
        from .mutants import apply

        apply(monkeypatch, name)
    yield


def pytest_collection_modifyitems(config, items):
    if config.getoption("--mutant") is None:
        return
    keep, drop = [], []
    for item in items:
        callspec = getattr(item, "callspec", None)
        planted = callspec is not None and callspec.params.get("mutant") is not None
        (drop if planted else keep).append(item)
    if drop:
        config.hook.pytest_deselected(items=drop)
        items[:] = keep


_FAILURES: dict[str, dict] = {}


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    report = outcome.get_result()
    if item.config.getoption("--teeth-out") is None or not report.failed:
        return  # passed, skipped, or still the expected failure
    excinfo = call.excinfo
    kind = "XPASS(strict)" if excinfo is None else excinfo.type.__name__
    message = "" if excinfo is None else str(excinfo.value).strip().split("\n")[0]
    _FAILURES.setdefault(
        item.nodeid, {"when": report.when, "error": kind, "message": message[:200]}
    )


def pytest_sessionfinish(session):
    out = session.config.getoption("--teeth-out")
    if out is not None:
        Path(out).write_text(json.dumps(_FAILURES, indent=1))


# script


def run(mutant: str | None, folder: Path) -> dict:
    """Failures of one run of the ZI suite, with ``mutant`` planted (or none)."""
    out = folder / f"{mutant or 'driver'}.json"
    command = [
        sys.executable,
        "-m",
        "pytest",
        SUITE,
        "-q",
        "--no-cov",
        "-p",
        "no:cacheprovider",
        "-p",
        PLUGIN,
        "--teeth-out",
        str(out),
    ]
    if mutant is not None:
        command += ["--mutant", mutant]
    done = subprocess.run(
        command, check=False, cwd=ROOT, capture_output=True, text=True
    )
    if not out.exists():
        raise RuntimeError(f"No result for {mutant}:\n{done.stdout[-2000:]}")
    return json.loads(out.read_text())


def function(nodeid: str) -> str:
    """``<file>::<test function>`` of a node id, without parameters."""
    path, _, name = nodeid.partition("::")
    return f"{Path(path).name}::{name.partition('[')[0]}"


def area(name: str) -> str:
    file = name.partition("::")[0]
    if file.startswith("test_effects_") or file == "test_references.py":
        return "effect"
    if file in ("test_conformance.py", "test_checkpoints.py"):
        return "contract"
    return "driver"


AREAS = {
    "driver": "driver tests (tests/instruments/zi/test_*.py)",
    "contract": "contract tests (test_conformance.py, test_checkpoints.py)",
    "effect": "effect tests (test_effects_*.py, test_references.py)",
}


def caught_how(failures: list[dict]) -> str:
    kinds = {f["error"] for f in failures}
    if kinds & {"AssertionError", "Missing", "Failed", "XPASS(strict)"}:
        return "assertion"
    if any("LabOneQ" in k for k in kinds):
        return "LabOne Q refusal only"
    return "crash only"


def report(mutants: dict, baseline: dict, results: dict) -> str:
    laboneq = version("laboneq")
    lines = [
        "# Teeth matrix",
        "",
        (
            f"Generated by `python -m {PLUGIN}` with laboneq {laboneq}, on the whole ZI "
            f"suite ({SUITE}). Each row plants one driver bug from mutants.py in every "
            "test and lists the tests that turn red. `@kills` cases are deselected; the "
            "`[driver]` case of each effect test runs on the mutated driver instead."
        ),
        "",
        (
            "Caught by: `assertion` = at least one test fails on an assertion (or a strict "
            "xfail no longer holds); `LabOne Q refusal only` = only LabOne Q rejects the "
            "experiment; `crash only` = tests fail with other exceptions only. A mutant "
            "no test turns red is a gap."
        ),
        "",
    ]
    if baseline:
        lines += [
            "Left out because they do not pass on the driver itself: "
            + ", ".join(f"`{n}`" for n in sorted(baseline))
            + ".",
            "",
        ]
    gaps = [m for m in mutants if not results[m]]
    lines += [
        "## Summary",
        "",
        f"{len(mutants) - len(gaps)} of {len(mutants)} planted bugs turn at least one "
        "test red. "
        + ("Gaps: " + ", ".join(f"`{g}`" for g in gaps) + "." if gaps else "No gaps."),
        "",
        (
            "| planted bug | what it does | caught by | driver tests | contract tests "
            "| effect tests |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for name, description in mutants.items():
        failures = results[name]
        per_area = defaultdict(set)
        for nodeid in failures:
            per_area[area(function(nodeid))].add(function(nodeid))
        how = caught_how(list(failures.values())) if failures else "**gap**"
        counts = " | ".join(str(len(per_area[a])) for a in AREAS)
        lines.append(f"| `{name}` | {description} | {how} | {counts} |")
    lines += [
        "",
        "Counts are test functions (all parametrized cases of one function count once).",
        "",
        "## Tests that fail, per planted bug",
        "",
    ]
    for name, description in mutants.items():
        failures = results[name]
        lines += [f"### `{name}`", "", description + ".", ""]
        if not failures:
            lines += ["**Gap:** no test of the suite fails.", ""]
            continue
        by_function = defaultdict(list)
        for nodeid, failure in failures.items():
            by_function[function(nodeid)].append(failure)
        for key, title in AREAS.items():
            names = sorted(n for n in by_function if area(n) == key)
            if not names:
                lines.append(f"- {title}: none")
                continue
            lines.append(f"- {title}:")
            for n in names:
                errors = sorted({f["error"] for f in by_function[n]})
                cases = len(by_function[n])
                lines.append(
                    f"  - `{n}` ({cases} case{'s' if cases > 1 else ''}; "
                    f"{', '.join(errors)})"
                )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("-k", default="", help="Only mutants containing this.")
    parser.add_argument("--out", type=Path, default=HERE / "TEETH.md")
    args = parser.parse_args()

    sys.path.insert(0, str(ROOT))
    from tests.instruments.zi.conformance.mutants import MUTANTS

    mutants = {n: m.description for n, m in MUTANTS.items() if args.k in n}
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        baseline = run(None, folder)
        with ThreadPoolExecutor(args.jobs) as pool:
            runs = dict(zip(mutants, pool.map(lambda m: run(m, folder), mutants)))
    results = {
        name: {n: f for n, f in failures.items() if n not in baseline}
        for name, failures in runs.items()
    }
    args.out.write_text(report(mutants, baseline, results))
    for name in mutants:
        print(f"{name}: {len(results[name])} failing cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
